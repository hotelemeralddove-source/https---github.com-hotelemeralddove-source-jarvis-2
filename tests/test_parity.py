"""The "what is missing?" list must be generated, current, and true

    python tests/test_parity.py

The user's request: *"sandbox-la run pana pothu yethu irukku, adhu .exe-layum
irukanum — oru file la kodu."* A list like that is only worth having if it is not
hand-typed, because it goes stale the moment a dependency or a model is added, and a
stale list is worse than none: it sends somebody downloading 1.5 GB they did not need.

So the rules here are about the *generator*, not the prose:

  1. `WHATS_INCLUDED.md` matches what `tools/parity.py` produces right now;
  2. every module of the app is collected by the build (no hand-written list);
  3. every helper script the frozen app reads at runtime is in the spec's datas —
     `tools/clone_speak.py` is the one that turns a downloaded voice engine into speech;
  4. the wake engine is collected, so "hey gamvis" cannot be silent in the .exe;
  5. the file says where things go, so "missing" always has a destination.
"""
from __future__ import annotations

import os
import sys
import tempfile

os.environ["ARCDESK_HOME"] = tempfile.mkdtemp(prefix="arcdesk-parity-")
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from pathlib import Path  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

ok = True


def check(label: str, got, want=True) -> None:
    global ok
    good = got == want
    print(f"   {'OK  ' if good else 'FAIL'} {label:<58} {str(got)[:46]!r}")
    ok &= bool(good)


print("1) the file is generated, and it is current")
import parity  # noqa: E402

doc = ROOT / "WHATS_INCLUDED.md"
check("the document exists", doc.is_file(), True)
text = doc.read_text(encoding="utf-8")
check("it is byte-identical to a fresh generation", text.strip(), parity.report().strip())
check("generating it again changes nothing", parity.main(["--check"]), 0)
check("it declares itself generated", "Generated by `python tools/parity.py`" in text, True)

print("\n2) every module of the app ships (no hand-written list)")
spec = (ROOT / "packaging" / "arcdesk.spec").read_text(encoding="utf-8")
modules = sorted((ROOT / "arcdesk").rglob("*.py"))
check("the count in the document is the real count",
      f"**{len(modules)} Python modules**" in text, True)
check("the spec collects them by package, not by name",
      'collect_submodules("arcdesk")' in spec, True)
check("…so a module added today is in tomorrow's .exe",
      "hiddenimports = collect_submodules" in spec, True)

print("\n3) the helper scripts the frozen app reads are carried as data")
for name in ("doctor.py", "clone_speak.py"):
    check(f"tools/{name} is in the spec's datas", f'"{name}"' in spec, True)
    check(f"…and the document says it is shipped", f"tools/{name}  ✔ shipped as data" in text,
          True)
check("clone_speak.py really exists", (ROOT / "tools" / "clone_speak.py").is_file(), True)
check("the brain module can find it when frozen", "script_path" in
      (ROOT / "arcdesk" / "engines.py").read_text(encoding="utf-8"), True)

print("\n4) the ears are collected, so the .exe can hear")
check("the spec asks PyInstaller for vosk",
      '"vosk"' in spec and "collect_submodules(_mod)" in spec, True)
check("the document says the wake engine ships", "collected by the spec" in text, True)

print("\n5) everything that is NOT in the .exe has a stated size and a destination")
for needle in ("vosk-model-small-en-us-0.15", "engine_env", "ArcDesk\\models",
               "%APPDATA%\\ArcDesk\\vault", "llama-cpp-python"):
    check(f"the document names {needle}", needle in text, True)
for size in ("40 MB", "30 MB", "1066 MB", "1.5 GB", "1.9 GB"):
    check(f"the size {size} is stated", size in text, True)
check("it explains why weights are not inside a 53 MB installer",
      "cannot import a package that arrives later" in text, True)
check("it ends with the five first-run steps, no command prompt",
      "Nothing on that list needs a command prompt" in text, True)

print("\n6) the sandbox column is measured, not assumed")
check("a library whose import fails is not claimed as a clean yes",
      "import fails here" in text or all(parity.have(m) in ("yes", "no")
                                         for m, *_ in parity.LIBS), True)
check("have() distinguishes installed from importable",
      parity.have("sys") , "yes")
check("a package that is absent reads as no", parity.have("definitely_not_installed_xyz"),
      "no")

print()
print("RESULT:", "ALL PASS" if ok else "FAILURES ABOVE")
raise SystemExit(0 if ok else 1)
